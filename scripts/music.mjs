import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { args, allowArgs, main, writeJson } from './lib-cli.mjs';
import '../workbench/sample-bank.js';
import '../workbench/music-engine.js';
await main(async () => {
  const o = args(); allowArgs(o, ['out','preset','duration','bpm','key','mode']);
  if(o._.length!==2 || !['init','render'].includes(o._[0])) throw Error('用法：node scripts/music.mjs init <新工作台目录> [--preset cinema|warm|pulse] [--duration 32]；或 render <score.json> --out <score.wav>');
  const M=globalThis.MusicScore;
  if(o._[0]==='init') {
    if(o.out)throw Error('init 的目标目录直接作为参数提供');
    const target=path.resolve(o._[1]);if(fs.existsSync(target))throw Error('工作台目录已存在，请使用新目录');
    const input={};for(const k of ['preset','mode'])if(o[k]!==undefined)input[k]=o[k];for(const k of ['duration','bpm','key'])if(o[k]!==undefined)input[k]=Number(o[k]);
    const c=M.config({...input,title:path.basename(target)}), source=fileURLToPath(new URL('../workbench/',import.meta.url));
    fs.mkdirSync(target,{recursive:true});for(const f of fs.readdirSync(source))if(fs.statSync(path.join(source,f)).isFile())fs.copyFileSync(path.join(source,f),path.join(target,f));
    fs.writeFileSync(path.join(target,'score-config.js'),'window.MUSIC_WORKBENCH_DEFAULTS = '+JSON.stringify(c,null,2)+';\n');
    console.log('配乐工作台已创建：'+path.join(target,'index.html')+'\n双击打开，先试听，再保存 WAV、方案与时间轴。');
  } else {
    if(!o.out || !/\.wav$/i.test(o.out))throw Error('render 需要 --out 指定新的 WAV 文件');
    if(['preset','duration','bpm','key','mode'].some(k=>o[k]!==undefined))throw Error('render 的音乐参数请写入 score.json');
    const output=path.resolve(o.out), base=output.replace(/\.wav$/i,''), configFile=base+'.json', timeline=base+'.timeline.js', midi=base+'.mid',credits=base+'.credits.txt';
    for(const f of [output,configFile,timeline,midi,credits])if(fs.existsSync(f))throw Error('输出已存在，请使用新名称：'+f);
    const score=M.plan(JSON.parse(fs.readFileSync(o._[1],'utf8').replace(/^\uFEFF/,''))), rendered=await M.render(score,{sampleRate:48000}), audio=M.mix(rendered);
    fs.mkdirSync(path.dirname(output),{recursive:true});fs.writeFileSync(output,M.wav(audio),{flag:'wx'});writeJson(configFile,score.config);
    fs.writeFileSync(timeline,'window.MUSIC_TIMELINE = '+JSON.stringify(M.timeline(score),null,2)+';\n',{flag:'wx'});
    fs.writeFileSync(midi,M.midi(score),{flag:'wx'});
    fs.writeFileSync(credits,(audio.credits||'Original composition generated by Score Room using procedural synthesis.')+'\n',{flag:'wx'});
    console.log(`已生成 ${output}\n${score.duration}s · ${score.bpm} BPM · 48 kHz stereo · 峰值 ${(20*Math.log10(audio.peak)).toFixed(1)} dBFS\n将 WAV 放入项目并接入 audio.src；先在 HTML 中试听。`);
  }
});
